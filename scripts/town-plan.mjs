/* 生成小镇规划 ASCII 图（35 列 × 20 行，对应 x33-67 / y1-20） */
const W = 35, H = 20;
const grid = Array.from({ length: H }, () => Array(W).fill('.'));

const col = (x) => x - 33;
const row = (y) => y - 1;

function fill(x0, y0, w, h, ch) {
  for (let y = y0; y < y0 + h; y++)
    for (let x = x0; x < x0 + w; x++)
      if (col(x) >= 0 && col(x) < W && row(y) >= 0 && row(y) < H) grid[row(y)][col(x)] = ch;
}

// 树（外围一行）
for (let c = 0; c < W; c++) grid[0][c] = '▓';

/* ── 路网 ──
   主街 y8：x33-45（西入口，到广场西沿）
   广场  ：x46-54, y8-13（9×6）
   东街 y8：x55-67（广场东沿 → 东端）
   南巷 x43：y9-17（主街末段 → 南区）
   河岸 y18：全宽
   河   y19-20
*/
fill(33, 8, 13, 1, '═');   // 主街 x33-45
fill(55, 8, 8, 1, '═');    // 东街 x55-62（x63 起是树林）
fill(46, 7, 9, 7, '▒');    // 广场（y7-13，北沿紧贴建筑）
fill(43, 9, 1, 9, '┼');    // 南巷
fill(33, 18, 35, 1, '-');  // 河岸
fill(33, 19, 35, 2, '≈');  // 河

/* ── 建筑 ── */
fill(34, 3, 4, 4, 'S');    // 杂货店   x34-37, y3-6   门 (35,6) 朝南
fill(39, 3, 3, 4, 'T');    // 酒馆     x39-41, y3-6   门 (40,6) 朝南
fill(44, 3, 4, 4, 'M');    // 铁匠铺   x44-47, y3-6   门 (45,6) 朝南
fill(49, 3, 5, 4, 'L');    // 学堂     x49-53, y3-6   门 (51,6) 朝南
fill(56, 3, 3, 4, 'C');    // 诊所     x56-58, y3-6   门 (57,6) 朝南
fill(60, 2, 3, 6, 'W');    // 钟楼     x60-62, y2-7   (不挡 y8)
fill(35, 10, 3, 3, 'h');   // 民宅A    x35-37, y10-12 门朝东
fill(35, 14, 3, 3, 'h');   // 民宅B    x35-37, y14-16
fill(39, 15, 3, 3, 'h');   // 民宅C    x39-41, y15-17
fill(48, 14, 3, 3, 'h');   // 民宅D    x48-50, y14-16（紧贴广场南沿）
fill(52, 14, 3, 3, 'h');   // 民宅E    x52-54, y14-16
fill(57, 14, 3, 3, 'h');   // 民宅F    x57-59, y14-16

/* ── 标志物 ── */
fill(39, 10, 2, 2, 'w');       // 水井（南巷西侧空地）
fill(44, 15, 3, 2, 'v');       // 小菜园（南巷东侧）
fill(63, 2, 5, 16, '♣');      // 东侧树林（y2-17）
fill(49, 9, 3, 3, 'O');        // 喷泉
grid[row(8)][col(46)] = 'b';   // 委托板（广场西沿）
grid[row(12)][col(47)] = 'n';  // 长椅
grid[row(12)][col(53)] = 'n';  // 长椅
grid[row(7)][col(54)] = '*';  // 花坛
grid[row(7)][col(46)] = '*';  // 花坛

/* ── 输出 ── */
let out = '';
out += '      ' + Array.from({ length: W }, (_, i) => String((33 + i) % 10)).join('') + '   ← x 的个位\n';
out += '     ' + '─'.repeat(W) + '\n';
for (let r = 0; r < H; r++) {
  out += 'y' + String(r + 1).padStart(2, ' ') + '  ' + grid[r].join('') + '\n';
}
console.log(out);